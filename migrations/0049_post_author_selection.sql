-- 0049: 게시글 "게시자 선택" 기능 + 실수노트 완전 익명화
--
-- 배경
--   병원은 컴퓨터마다 로그인 계정이 다르고, 같은 컴퓨터를 여러 직원이
--   돌아가며 쓴다. 즉 "로그인한 사람 = 실제로 이 글을 쓴 사람"이 아니다.
--   → 일반 게시판(공지/자유/칭찬)은 글쓰기 시 "게시자"를 직접 선택하게 한다.
--   → 실수노트는 애초에 게시자 개념 자체가 필요 없다 (완전 익명 게시판).
--     로그인 계정(author_id)은 오직 삭제 권한/감사 로그용으로만 내부에 남고
--     API 응답에서는 절대 노출하지 않는다 (기존 is_anonymous 마스킹 로직 재사용).
-- ════════════════════════════════════════════════════════════════════

-- 게시자로 "선택된" 사용자. NULL이면 로그인 계정 이름을 그대로 표시.
-- author_id(로그인 세션 계정)는 삭제 권한/피드백 권한 판정용으로 그대로 둔다.
ALTER TABLE posts ADD COLUMN posted_as_id TEXT REFERENCES users(id) DEFAULT NULL;

CREATE INDEX IF NOT EXISTS idx_posts_posted_as ON posts(posted_as_id);
